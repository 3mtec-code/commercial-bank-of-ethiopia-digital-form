import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:intl/intl.dart';
import '../form/models/transaction_model.dart';

class PdfGenerator {
  static Future<void> generateAndShare(TransactionModel tx) async {
    final pdf = await _buildPdf(tx);
    await Printing.sharePdf(
      bytes: pdf,
      filename: '${tx.referenceNumber}.pdf',
    );
  }

  static Future<Uint8List> generateBytes(TransactionModel tx) async {
    return _buildPdf(tx);
  }

  static Future<Uint8List> _buildPdf(TransactionModel tx) async {
    final doc = pw.Document();
    final isDeposit = tx.formType.contains('Deposit');

    // Color scheme
    final primaryColor = PdfColor.fromHex('#4A0E4E');
    final accentColor = isDeposit
        ? PdfColor.fromHex('#10B981')
        : PdfColor.fromHex('#6D28D9');
    final lightGray = PdfColor.fromHex('#F9FAFB');
    final borderColor = PdfColor.fromHex('#E5E7EB');
    final textSecondary = PdfColor.fromHex('#6B7280');

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (ctx) => _buildHeader(primaryColor, accentColor, tx, isDeposit),
        footer: (ctx) => _buildFooter(ctx, primaryColor),
        build: (ctx) => [
          pw.SizedBox(height: 16),

          // Reference + Status row
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              _infoBox(
                label: 'Reference Number',
                value: tx.referenceNumber,
                color: primaryColor,
                lightGray: lightGray,
              ),
              _infoBox(
                label: 'Date',
                value: tx.date,
                color: primaryColor,
                lightGray: lightGray,
              ),
              _infoBox(
                label: 'Status',
                value: tx.status.toUpperCase(),
                color: accentColor,
                lightGray: lightGray,
              ),
            ],
          ),

          pw.SizedBox(height: 16),

          // Account Information
          _sectionCard(
            title: 'Account Information',
            color: primaryColor,
            lightGray: lightGray,
            borderColor: borderColor,
            textSecondary: textSecondary,
            rows: [
              ['Account Holder', tx.accountHolderName],
              ['Account Number', tx.accountNumber],
              ['Account Type', tx.accountType],
              ['Branch', tx.branch],
            ],
          ),

          pw.SizedBox(height: 12),

          // Denomination breakdown
          _denominationTable(tx, primaryColor, accentColor, lightGray, borderColor, textSecondary),

          pw.SizedBox(height: 12),

          // Transaction details
          _sectionCard(
            title: 'Transaction Details',
            color: accentColor,
            lightGray: lightGray,
            borderColor: borderColor,
            textSecondary: textSecondary,
            rows: [
              ['Form Type', tx.formType],
              ['Amount (ETB)', _fmtAmount(tx.totalAmount)],
              ['Amount in Words', tx.amountInWords],
              ['Source of Proceeds', tx.sourceOfProceeds],
              [isDeposit ? 'Deposited By' : 'Withdrawn By', tx.depositedBy],
              ['Phone Number', tx.phoneNumber],
            ],
          ),

          pw.SizedBox(height: 12),

          // Signature area
          _signatureSection(tx, primaryColor, lightGray, borderColor),

          pw.SizedBox(height: 16),

          // Security notice
          pw.Container(
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#F0FDF9'),
              borderRadius: pw.BorderRadius.circular(8),
              border: pw.Border.all(color: PdfColor.fromHex('#6EE7B7')),
            ),
            child: pw.Row(
              children: [
                pw.Text('🔒 ', style: const pw.TextStyle(fontSize: 11)),
                pw.Expanded(
                  child: pw.Text(
                    'This document is digitally generated by CBE Digital Banking Form Service. '
                    'Reference: ${tx.referenceNumber}. AES-256 Encrypted.',
                    style: pw.TextStyle(
                      fontSize: 9,
                      color: PdfColor.fromHex('#065F46'),
                    ),
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );

    return doc.save();
  }

  // ── Header ──────────────────────────────────────────────────────────────────
  static pw.Widget _buildHeader(
    PdfColor primaryColor,
    PdfColor accentColor,
    TransactionModel tx,
    bool isDeposit,
  ) {
    return pw.Container(
      padding: const pw.EdgeInsets.only(bottom: 12),
      decoration: pw.BoxDecoration(
        border: pw.Border(
          bottom: pw.BorderSide(color: primaryColor, width: 2),
        ),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                'COMMERCIAL BANK OF ETHIOPIA',
                style: pw.TextStyle(
                  fontSize: 14,
                  fontWeight: pw.FontWeight.bold,
                  color: primaryColor,
                ),
              ),
              pw.Text(
                'የኢትዮጵያ ንግድ ባንክ',
                style: pw.TextStyle(
                  fontSize: 11,
                  color: primaryColor,
                ),
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                isDeposit
                    ? 'CASH DEPOSIT VOUCHER'
                    : 'CASH WITHDRAWAL FORM',
                style: pw.TextStyle(
                  fontSize: 12,
                  fontWeight: pw.FontWeight.bold,
                  color: accentColor,
                  letterSpacing: 1.5,
                ),
              ),
            ],
          ),
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              pw.Container(
                padding: const pw.EdgeInsets.symmetric(
                    horizontal: 12, vertical: 6),
                decoration: pw.BoxDecoration(
                  color: accentColor,
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Text(
                  isDeposit ? 'DEPOSIT' : 'WITHDRAWAL',
                  style: const pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 11,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                'Digital Banking Form Service',
                style: pw.TextStyle(
                  fontSize: 9,
                  color: PdfColor.fromHex('#9CA3AF'),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }

  // ── Footer ──────────────────────────────────────────────────────────────────
  static pw.Widget _buildFooter(pw.Context ctx, PdfColor primaryColor) {
    final now = DateFormat('dd MMM yyyy HH:mm').format(DateTime.now());
    return pw.Container(
      padding: const pw.EdgeInsets.only(top: 8),
      decoration: pw.BoxDecoration(
        border: pw.Border(
          top: pw.BorderSide(color: PdfColor.fromHex('#E5E7EB')),
        ),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Generated: $now',
            style: pw.TextStyle(
                fontSize: 8, color: PdfColor.fromHex('#9CA3AF')),
          ),
          pw.Text(
            'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
            style: pw.TextStyle(
                fontSize: 8, color: PdfColor.fromHex('#9CA3AF')),
          ),
          pw.Text(
            'CBE Digital Form v1.0',
            style: pw.TextStyle(
                fontSize: 8, color: PdfColor.fromHex('#9CA3AF')),
          ),
        ],
      ),
    );
  }

  // ── Info Box ─────────────────────────────────────────────────────────────────
  static pw.Widget _infoBox({
    required String label,
    required String value,
    required PdfColor color,
    required PdfColor lightGray,
  }) {
    return pw.Container(
      width: 155,
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        color: lightGray,
        borderRadius: pw.BorderRadius.circular(8),
        border: pw.Border.all(color: PdfColor.fromHex('#E5E7EB')),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            label,
            style: pw.TextStyle(
                fontSize: 8, color: PdfColor.fromHex('#9CA3AF')),
          ),
          pw.SizedBox(height: 3),
          pw.Text(
            value,
            style: pw.TextStyle(
              fontSize: 11,
              fontWeight: pw.FontWeight.bold,
              color: color,
            ),
          ),
        ],
      ),
    );
  }

  // ── Section Card ─────────────────────────────────────────────────────────────
  static pw.Widget _sectionCard({
    required String title,
    required PdfColor color,
    required PdfColor lightGray,
    required PdfColor borderColor,
    required PdfColor textSecondary,
    required List<List<String>> rows,
  }) {
    return pw.Container(
      decoration: pw.BoxDecoration(
        borderRadius: pw.BorderRadius.circular(8),
        border: pw.Border.all(color: borderColor),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.symmetric(
                horizontal: 12, vertical: 8),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromInt(color.toInt()).shade(0.9),
              borderRadius: const pw.BorderRadius.only(
                topLeft: pw.Radius.circular(8),
                topRight: pw.Radius.circular(8),
              ),
            ),
            child: pw.Text(
              title,
              style: pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
                color: color,
              ),
            ),
          ),
          pw.Padding(
            padding: const pw.EdgeInsets.all(12),
            child: pw.Table(
              columnWidths: {
                0: const pw.FlexColumnWidth(1),
                1: const pw.FlexColumnWidth(2),
              },
              children: rows.map((row) {
                return pw.TableRow(
                  children: [
                    pw.Padding(
                      padding: const pw.EdgeInsets.symmetric(vertical: 3),
                      child: pw.Text(
                        row[0],
                        style: pw.TextStyle(
                            fontSize: 9, color: textSecondary),
                      ),
                    ),
                    pw.Padding(
                      padding: const pw.EdgeInsets.symmetric(vertical: 3),
                      child: pw.Text(
                        row[1],
                        style: pw.TextStyle(
                          fontSize: 10,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColor.fromHex('#111827'),
                        ),
                      ),
                    ),
                  ],
                );
              }).toList(),
            ),
          ),
        ],
      ),
    );
  }

  // ── Denomination Table ────────────────────────────────────────────────────────
  static pw.Widget _denominationTable(
    TransactionModel tx,
    PdfColor primaryColor,
    PdfColor accentColor,
    PdfColor lightGray,
    PdfColor borderColor,
    PdfColor textSecondary,
  ) {
    final activeRows = tx.denominations.entries
        .where((e) => e.value > 0)
        .toList()
      ..sort((a, b) {
        final da = double.tryParse(a.key) ?? 0;
        final db = double.tryParse(b.key) ?? 0;
        return db.compareTo(da);
      });

    if (activeRows.isEmpty) return pw.SizedBox();

    return pw.Container(
      decoration: pw.BoxDecoration(
        borderRadius: pw.BorderRadius.circular(8),
        border: pw.Border.all(color: borderColor),
      ),
      child: pw.Column(
        children: [
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.symmetric(
                horizontal: 12, vertical: 8),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromInt(primaryColor.toInt()).shade(0.9),
              borderRadius: const pw.BorderRadius.only(
                topLeft: pw.Radius.circular(8),
                topRight: pw.Radius.circular(8),
              ),
            ),
            child: pw.Text(
              'Denomination Breakdown',
              style: pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
                color: primaryColor,
              ),
            ),
          ),
          pw.Padding(
            padding: const pw.EdgeInsets.all(12),
            child: pw.Column(
              children: [
                // Table header
                pw.Row(
                  children: [
                    pw.Expanded(
                        child: pw.Text('Denomination',
                            style: pw.TextStyle(
                                fontSize: 9,
                                fontWeight: pw.FontWeight.bold,
                                color: textSecondary))),
                    pw.SizedBox(width: 60,
                        child: pw.Center(
                            child: pw.Text('Qty',
                                style: pw.TextStyle(
                                    fontSize: 9,
                                    fontWeight: pw.FontWeight.bold,
                                    color: textSecondary)))),
                    pw.SizedBox(width: 80,
                        child: pw.Align(
                            alignment: pw.Alignment.centerRight,
                            child: pw.Text('Amount',
                                style: pw.TextStyle(
                                    fontSize: 9,
                                    fontWeight: pw.FontWeight.bold,
                                    color: textSecondary)))),
                  ],
                ),
                pw.Divider(color: borderColor),
                ...activeRows.map((e) {
                  final denom = double.tryParse(e.key) ?? 0;
                  final qty = e.value;
                  final lineTotal = denom * qty;
                  return pw.Padding(
                    padding: const pw.EdgeInsets.symmetric(vertical: 2),
                    child: pw.Row(
                      children: [
                        pw.Expanded(
                            child: pw.Text(
                                'ETB ${denom >= 1 ? denom.toStringAsFixed(0) : denom.toStringAsFixed(2)}',
                                style: const pw.TextStyle(fontSize: 9))),
                        pw.SizedBox(
                            width: 60,
                            child: pw.Center(
                                child: pw.Text('× $qty',
                                    style: const pw.TextStyle(fontSize: 9)))),
                        pw.SizedBox(
                            width: 80,
                            child: pw.Align(
                                alignment: pw.Alignment.centerRight,
                                child: pw.Text(
                                    _fmtAmount(lineTotal),
                                    style: const pw.TextStyle(
                                        fontSize: 9,
                                        fontWeight: pw.FontWeight.bold)))),
                      ],
                    ),
                  );
                }),
                pw.Divider(color: borderColor),
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text('Total',
                        style: const pw.TextStyle(
                            fontSize: 11,
                            fontWeight: pw.FontWeight.bold)),
                    pw.Text('ETB ${_fmtAmount(tx.totalAmount)}',
                        style: pw.TextStyle(
                            fontSize: 12,
                            fontWeight: pw.FontWeight.bold,
                            color: accentColor)),
                  ],
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

