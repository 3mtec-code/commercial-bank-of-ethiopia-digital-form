                    style: pw.TextStyle(
                        fontSize: 9,
                        color: PdfColor.fromHex('#9CA3AF'))),
                pw.Spacer(),
                if (tx.signatureData != null && tx.signatureData!.isNotEmpty)
                  pw.Center(
